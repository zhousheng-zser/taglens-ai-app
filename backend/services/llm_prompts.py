def build_default_analysis_prompt(
    camera_name: Optional[str] = None,
    camera_structure: Optional[str] = None,
) -> str:
    """构造默认交通图片分析 Prompt。"""
    if camera_name and camera_structure and camera_structure != "未知区域":
        part2 = PROMPT_PART_2_TEMPLATE.format(
            camera_name=camera_name,
            camera_structure=camera_structure,
        )
        return PROMPT_PART_1 + "\n" + part2 + "\n" + PROMPT_PART_3
    return PROMPT_PART_1 + "\n" + PROMPT_PART_3
